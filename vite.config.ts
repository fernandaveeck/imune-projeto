import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { ViteDevServer } from "vite";
import { defineConfig } from "@lovable.dev/vite-tanstack-config";

const isVercel = Boolean(process.env.VERCEL);
const routeTreeFile = path.resolve(process.cwd(), "src/routeTree.gen.ts");
const generatedHeader = /^\/\* eslint-disable \*\/\r?\n\r?\n\/\/ @ts-nocheck\r?\n\r?\n\/\/ noinspection JSUnusedGlobalSymbols\r?\n\r?\n\/\/ This file was automatically generated by TanStack Router\.\r?\n\/\/ You should NOT make any changes in this file as it will be overwritten\.\r?\n\/\/ Additionally, you should also exclude this file from your linter and\/or formatter to prevent it from being checked or modified\.\r?\n\r?\n/;

function removeGeneratedRouteTreeComments() {
	let cleaning = false;
	const clean = async () => {
		if (cleaning) return;
		cleaning = true;
		try {
			const source = await readFile(routeTreeFile, "utf8");
			const updated = source.replace(generatedHeader, "");
			if (updated !== source) await writeFile(routeTreeFile, updated);
		} catch {
			return;
		} finally {
			cleaning = false;
		}
	};

	return {
		name: "remove-generated-route-tree-comments",
		enforce: "post" as const,
		configureServer(server: ViteDevServer) {
			server.watcher.on("change", (file) => {
				if (path.resolve(file) === routeTreeFile) void clean();
			});
			void clean();
		},
		async closeBundle() {
			await clean();
		},
	};
}

export default defineConfig({
	vite: { plugins: [removeGeneratedRouteTreeComments()] },
	tanstackStart: {
		server: { entry: "server" },

		...(isVercel
			? {
					nitro: {
						preset: "vercel",
					},
				}
			: {}),
	},
});
